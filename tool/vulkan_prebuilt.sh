#!/usr/bin/env bash
# Regenerates src/vulkan_prebuilt: ggml's Vulkan shaders compiled ahead of
# time, plus the Vulkan and SPIR-V headers, for the Android Vulkan backend
# (Veemoo fork; see src/vulkan_prebuilt/README.md).
#
# Run on Linux or macOS after any change to src/llama.cpp/ggml/src/ggml-vulkan:
#   tool/vulkan_prebuilt.sh GLSLC VULKAN_HEADERS_DIR SPIRV_HEADERS_DIR
# GLSLC is a recent shaderc glslc (one that supports GL_EXT_integer_dot_product
# and GL_EXT_bfloat16). The header dirs are checkouts of KhronosGroup's
# Vulkan-Headers and SPIRV-Headers.
set -euo pipefail

glslc=$(realpath "$1")
vulkan_headers=$(realpath "$2")
spirv_headers=$(realpath "$3")
root=$(cd "$(dirname "$0")/.." && pwd)
vk="$root/src/llama.cpp/ggml/src/ggml-vulkan"
out="$root/src/vulkan_prebuilt"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Same feature tests as ggml-vulkan/CMakeLists.txt.
defines=()
check() { # extension test-file define
  if "$glslc" -o /dev/null -fshader-stage=compute --target-env=vulkan1.3 \
      "$vk/vulkan-shaders/feature-tests/$2" 2>&1 |
      grep -q "extension not supported: $1"; then
    echo "glslc: no $1"
  else
    echo "glslc: $1"
    defines+=("$3")
  fi
}
check GL_KHR_cooperative_matrix coopmat.comp GGML_VULKAN_COOPMAT_GLSLC_SUPPORT
# Not GL_NV_cooperative_matrix2: only NVIDIA GPUs run it, and no Android
# phone has one. Leaving it out keeps its shaders out of the APK.
check GL_EXT_integer_dot_product integer_dot.comp GGML_VULKAN_INTEGER_DOT_GLSLC_SUPPORT
check GL_EXT_bfloat16 bfloat16.comp GGML_VULKAN_BFLOAT16_GLSLC_SUPPORT
check GL_EXT_float_e2m1 float_e2m1.comp GGML_VULKAN_FLOAT_E2M1_GLSLC_SUPPORT
check GL_EXT_float_e4m3 float_e4m3.comp GGML_VULKAN_FLOAT_E4M3_GLSLC_SUPPORT

# The generator, built for this machine with the same features.
cmake_args=()
for d in "${defines[@]}"; do cmake_args+=("-D$d=ON"); done
cmake -S "$vk/vulkan-shaders" -B "$work/gen" -DCMAKE_BUILD_TYPE=Release \
  "${cmake_args[@]}" >/dev/null
cmake --build "$work/gen" --parallel >/dev/null
gen="$work/gen/vulkan-shaders-gen"

rm -rf "$out/shaders" "$out/include"
mkdir -p "$out/shaders" "$out/include/spirv/unified1"
hpp="$out/shaders/ggml-vulkan-shaders.hpp"
"$gen" --output-dir "$work/spv" --target-hpp "$hpp"
for comp in "$vk"/vulkan-shaders/*.comp; do
  name=$(basename "$comp")
  "$gen" --glslc "$glslc" --source "$comp" --output-dir "$work/spv" \
    --target-hpp "$hpp" --target-cpp "$out/shaders/$name.cpp"
done
rm -f "$out"/shaders/*.d

cp -R "$vulkan_headers/include/vulkan" "$vulkan_headers/include/vk_video" \
  "$out/include/"
cp "$spirv_headers/include/spirv/unified1/spirv.hpp" \
  "$out/include/spirv/unified1/"

{
  echo "# Generated by tool/vulkan_prebuilt.sh. The glslc features the shaders"
  echo "# were compiled with; ggml-vulkan.cpp must be built with the same ones."
  echo "set(GGML_VULKAN_PREBUILT_DEFINES ${defines[*]})"
  echo "set(GGML_VULKAN_PREBUILT_GLSLC \"$("$glslc" --version | head -1)\")"
  echo "set(GGML_VULKAN_PREBUILT_VULKAN_HEADERS \"$(git -C "$vulkan_headers" describe --tags 2>/dev/null || echo unknown)\")"
} >"$out/features.cmake"
echo "Wrote $out ($(du -sh "$out" | cut -f1))"
